package oops;

public class ObjectClass {
    int x = 5;
    int y = 6;

    public static void main(String[] args) {
        ObjectClass myObj1 = new ObjectClass();  // Object 1
        ObjectClass myObj2 = new ObjectClass();  // Object 2
        System.out.println(myObj1.x);
        System.out.println(myObj2.y);
    }
}
